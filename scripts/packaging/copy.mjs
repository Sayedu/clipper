// Every piece of wording the packaging can use, per format. Each template is a
// function of the video's facts (facts.mjs) and returns null when the facts it
// needs aren't there — so nothing is ever made up. Rules baked in here:
//   - captions start with the format keyword ("Color war", "Find the cat", ...)
//   - nothing states the winner or an answer (reveal.mjs double-checks)
//   - no dashes anywhere, no engagement bait ("like = red wins")
//   - the closing question is a real question about the video
//
// Caption = line 1 (one of four styles) + line 2 (a question).

