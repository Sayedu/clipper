/** Evaluate a template list against facts: [{id, value}] for the ones that apply. */
export function available(list, facts) {
  const out = [];
  for (const [id, fn] of list) {
    let v;
    try { v = fn(facts); } catch { v = null; }
    if (v) out.push({ id, value: v });
  }
  return out;
}
